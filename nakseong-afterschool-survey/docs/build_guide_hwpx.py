def p(text="", bold=False, small=False):
    ref = BOLD if bold else SMALL if small else None
    return doc.add_paragraph(text, char_pr_id_ref=ref) if ref else doc.add_paragraph(text)

def h(text):
    doc.add_paragraph("")
    doc.add_heading(text, level=2)

def table(rows, widths):
    t = doc.add_table(len(rows), len(rows[0]))
    for r, row in enumerate(rows):
        for c, val in enumerate(row):
            t.set_cell_text(r, c, val)
            if r == 0:
                t.set_cell_shading(r, c, "#E8EEF7")
    try:
        t.set_column_widths(widths)
    except Exception:
        pass
    return t

